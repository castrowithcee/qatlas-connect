// source returns a Go file of exactly lines lines, padded with comments after body.
func source(lines int, header, body string) string {
	text := header + "package p\n" + body
	if pad := lines - strings.Count(text, "\n"); pad > 0 {
		text += strings.Repeat("//\n", pad)
	}
	return text
}

// longFunc is a function of exactly lines lines.
func longFunc(lines int) string {
	return "func Long() {\n" + strings.Repeat("\t_ = 0\n", lines-2) + "}\n"
}

// branchyFunc has complexity 1 + ifs.
func branchyFunc(ifs int) string {
	return "func Branchy(x int) {\n" + strings.Repeat("\tif x > 0 {\n\t}\n", ifs) + "}\n"
}

const generated = "// Code generated by hand. DO NOT EDIT.\n\n"

func TestCheck(t *testing.T) {
	tests := []struct {
		name       string
		files      map[string]string
		exceptions string
		want       []string
	}{
		{"within limits", map[string]string{"a.go": source(500, "", longFunc(60)+branchyFunc(14))}, "", nil},
		{"new file over limit", map[string]string{"a.go": source(501, "", "")}, "", []string{"a.go: 501 lines, allowed 500"}},
		{"test file limit", map[string]string{"a_test.go": source(1000, "", "")}, "", nil},
		{"test file over limit", map[string]string{"a_test.go": source(1001, "", "")}, "", []string{"a_test.go: 1001 lines, allowed 1000"}},
		{"long function", map[string]string{"a.go": source(0, "", longFunc(61))}, "", []string{"a.go:Long: 61 lines, allowed 60"}},
		{"long test function", map[string]string{"a_test.go": source(0, "", longFunc(61))}, "", []string{"a_test.go:Long: 61 lines"}},
		{"complex function", map[string]string{"a.go": source(0, "", branchyFunc(15))}, "", []string{"a.go:Branchy: complexity 16, allowed 15"}},
		{"excepted file at ceiling", map[string]string{"a.go": source(600, "", "")}, "a.go 600", nil},
		{"excepted file grown", map[string]string{"a.go": source(601, "", "")}, "a.go 600", []string{"a.go: 601 lines, allowed 600"}},
		{"excepted function grown", map[string]string{"a.go": source(0, "", longFunc(71))}, "a.go:Long 70 1", []string{"a.go:Long: 71 lines, allowed 70"}},
		{"exception raises only exceeded limit", map[string]string{"a.go": source(0, "", "func Long() {\n"+strings.Repeat("\tif true {\n\t}\n", 16)+strings.Repeat("\t_ = 0\n", 36)+"}\n")}, "a.go:Long 70 1", []string{"a.go:Long: complexity 17, allowed 15"}},
		{"exception under limit", map[string]string{"a.go": source(500, "", "")}, "a.go 600", []string{"exceptions.txt: a.go no longer exceeds a limit; remove the entry"}},
		{"exception for deleted file", map[string]string{}, "a.go 600", []string{"exceptions.txt: a.go no longer exceeds a limit"}},
		{"generated file", map[string]string{"a.go": source(900, generated, longFunc(80))}, "", nil},
		{"same file without header", map[string]string{"a.go": source(900, "", longFunc(80))}, "", []string{"a.go: 900 lines", "a.go:Long: 80 lines"}},
		{"testdata", map[string]string{"x/testdata/a.go": source(900, "", "")}, "", nil},
		{"method name", map[string]string{"a.go": source(0, "", "type T[K any] struct{}\n\nfunc (t *T[K]) "+strings.TrimPrefix(longFunc(61), "func "))}, "", []string{"a.go:(*T).Long: 61 lines"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			fsys := fstest.MapFS{}
			for name, text := range tt.files {
				fsys[name] = &fstest.MapFile{Data: []byte(text)}
			}
			found, err := measure(fsys)
			if err != nil {
				t.Fatal(err)
			}
			assertProblems(t, check(found, tt.exceptions, tt.exceptions), tt.want)
		})
	}
}

func TestExceptionsOnlyShrink(t *testing.T) {
	found := map[string]size{"a.go": {600, 0}, "b.go": {700, 0}}
	base := "# header\na.go 600\nb.go 700\n"
	assertProblems(t, check(found, "a.go 600\nb.go  700\r\n", base), nil)
	assertProblems(t, check(map[string]size{"b.go": {700, 0}}, "b.go 700\n", base), nil)
	assertProblems(t, check(found, "a.go 600\nb.go 701\n", base), []string{`"b.go 701" is not in baseline.txt`, "b.go: 700 lines, allowed 500"})
	assertProblems(t, check(found, "a.go 600\nb.go 700\nc.go 800\n", base), []string{`"c.go 800" is not in baseline.txt`})
	assertProblems(t, check(found, "a.go 600\na.go 600\nb.go 700\n", base), []string{"a.go is listed twice"})
	assertProblems(t, check(found, "a.go\nb.go 700\n", base+"a.go\n"), []string{`"a.go": want`, "a.go: 600 lines, allowed 500"})
}

func TestBaselinePinned(t *testing.T) {
	assertProblems(t, verifyBaseline(baseline), nil)
	assertProblems(t, verifyBaseline(strings.ReplaceAll(baseline, "\n", "\r\n")), nil)
	assertProblems(t, verifyBaseline(baseline+"c.go 800\n"), []string{"baseline.txt: changed"})
}

func TestComplexity(t *testing.T) {
	body := `func F(x int, c chan int) {
	for i := 0; i < x; i++ {
	}
	for range x {
	}
	switch x {
	case 1, 2:
	case 3:
	default:
	}
	select {
	case <-c:
	default:
	}
	if x > 0 && x < 9 || x == 20 {
	}
	_ = func() {
		if x > 1 {
		}
	}
}
`
	f, err := parser.ParseFile(token.NewFileSet(), "a.go", "package p\n"+body, 0)
	if err != nil {
		t.Fatal(err)
	}
	// 1 + for + range + two non-default cases + select case + if + && + || + if in the literal
	if got := complexity(f.Decls[0].(*ast.FuncDecl)); got != 10 {
		t.Fatalf("complexity = %d, want 10", got)
	}
}

func assertProblems(t *testing.T, got, want []string) {
	t.Helper()
	if len(got) != len(want) {
		t.Fatalf("problems = %q, want %d matching %q", got, len(want), want)
	}
	for i := range want {
		if !strings.Contains(got[i], want[i]) {
			t.Fatalf("problem %d = %q, want it to contain %q", i, got[i], want[i])
		}
	}
}
